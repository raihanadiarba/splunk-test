"""
JSON Entity
"""
# pylint: disable=useless-object-inheritance, no-else-return

from functools import reduce  # pylint: disable=redefined-builtin
import logging
import copy
import time

from agent import FieldNotFoundException, \
    SchemaValidationException, \
    InvalidJsonRequestException
from agent.common.helpers import generate_guid, is_string


# pylint: disable=too-few-public-methods
class View(object):
    """
    Simple class that would act as an enum to represent the view Type
    """
    # When view is set to public fields everything in the json will be visible
    PublicFields = 1
    # Remove temp fields
    TemporaryFields = 2
    # In some cases we do want to get the original obj instead of clone
    KeepOriginal = 4
    # Remove the ID field
    ValueFieldsOnly = 8
    RepositoryView = PublicFields
    LogView = PublicFields | ValueFieldsOnly
    RestView = PublicFields | TemporaryFields
# pylint: enable=too-few-public-methods


def _is_temporary(key):
    """Verify if current field is considered temporary
    """
    return key.startswith("@")


class JSONEntity(object):
    """
    Simple object which stores data in embedded dictionary,
    serializable to JSON
    """

    _ID_FIELD = None
    _VERSION_FIELD = None
    _TRACK_CHANGES = False
    _DEFAULTS = None

    COLLECTION = None

    def __init__(self, json=None, use_defaults=None, keep_original=False):
        """
        Initialize new JSONEntity

        * json - dictionary of key/values
        * use_defaults:
            - None - use default values only if _ID_FIELD has not been included in json
            - True - use default values
            - False - do not use default values
        """

        # Verify attributes of delivered class
        assert not self._ID_FIELD or isinstance(self._ID_FIELD, str)
        assert not self._VERSION_FIELD or isinstance(self._VERSION_FIELD, str)
        assert isinstance(self._TRACK_CHANGES, bool)
        assert not self._DEFAULTS or isinstance(self._DEFAULTS, dict)
        assert (self._DEFAULTS and self._ID_FIELD) or not self._DEFAULTS

        self._dirty = False
        self._logger = logging.getLogger(self.__class__.__name__)
        json = json if json else {}

        # set autogenerated fields
        self._json = json

        if not keep_original:
            if self._TRACK_CHANGES and "createdAt" not in self._json:
                now = time.time()
                self.set_value("createdAt", now)
            if self._ID_FIELD and self._ID_FIELD not in self._json:
                generated_id = generate_guid()
                self._logger.debug("Autogenerated id %s", generated_id)
                self.set_value(self._ID_FIELD, generated_id)
                if use_defaults is None:
                    use_defaults = True
            if self._VERSION_FIELD and self._VERSION_FIELD not in self._json:
                self._logger.debug("Assigned version 1")
                self.set_value(self._VERSION_FIELD, 1)
            if self._DEFAULTS and use_defaults:
                self.set_default_values()

    @property
    def objid(self):
        """Get entity ID
        """
        return self.get_value(self._ID_FIELD)

    @property
    def dirty(self):
        """Get if this entity is dirty
        """
        return self._dirty

    @property
    def id_field_name(self):
        """Get id field name
        """
        return self._ID_FIELD

    @dirty.setter
    def dirty(self, value):
        """Set if this entity is dirty
        """
        self._dirty = value

    def has_path(self, key):
        """Verify if current json entity has specified path
        """
        # Performance improvement: for string keys
        if is_string(key):
            return key in self._json
        try:
            self.get_value(key)
        except SchemaValidationException:
            return False
        except FieldNotFoundException:
            return False
        else:
            return True

    def set_value(self,
                  key,
                  value):
        """Set value

        Key should be a string
        Value will be converted to the JSON serializable value.
        Key starts with '@' considering temporary and will not be saved in KVStore
        """
        assert is_string(key)

        previous_value = self._json.get(key)
        self._json[key] = value
        if not _is_temporary(key):
            self.dirty |= previous_value != value

    def set_default_values(self):
        """Set all missing default values
        """
        for key, value in self._DEFAULTS.items():
            if key not in self._json:
                kval = value
                if hasattr(kval, "__call__"):
                    kval = kval()
                elif isinstance(kval, dict):
                    kval = copy.deepcopy(kval)
                self._json[key] = kval

    def set_values(self, dictionary):
        """Set all values
        """
        for key, value in dictionary.items():
            self.set_value(key, value)

    def del_value(self, key):
        """Delete value

        Key should be a string
        """
        assert isinstance(key, str)

        del self._json[key]
        if not _is_temporary(key):
            self.dirty = True

    def get_value(self, key, default=None, raise_error=True):
        """ Get value

        Key can be a string or tuple (path to subdictionary)
        By default, raise an error if the key does not exist and the default is None
        """
        # Performance improvement: for string keys
        if is_string(key):
            if key in self._json:
                return self._json[key]
            elif default is not None or not raise_error:
                return default
            else:
                raise FieldNotFoundException(key)
        assert isinstance(key, tuple)
        try:
            result = reduce(self.__reduce_field_for_get, key, self._json)
        except FieldNotFoundException:
            # If field was not found and default is specified - return it
            if default is not None or not raise_error:
                return default
            else:
                raise
        else:
            return result

    def update_embedded(self, key, obj):
        """
        Update embedded object
        """
        if not self.has_path(key):
            self.set_value(key, {})

        self.get_value(key).update(obj)
        self.dirty = True

    def json(self, view=View.RepositoryView):
        """Returns dictionary representation

        If TempFields is not specified all temporary fields will be removed
        from return value. Also to_save always returns copy
        """
        if view == View.KeepOriginal:
            return self._json

        if view | View.PublicFields != view:
            raise InvalidJsonRequestException()

        jsoncopy = copy.deepcopy(self._json)
        if view | View.TemporaryFields != view:
            for key in self._json:
                if _is_temporary(key):
                    del jsoncopy[key]

        if view & View.ValueFieldsOnly:
            if self._ID_FIELD in jsoncopy:
                del jsoncopy[self._ID_FIELD]

        return jsoncopy

    def match_values(self, values):
        """Verify if all values are matched
        """
        for key, value in values.items():
            if key not in self._json:
                return False
            if value != self._json[key]:
                return False
        return True

    @staticmethod
    def __reduce_field_for_get(obj, key):
        """Find field using path of k
        """
        if isinstance(obj, dict):
            if not is_string(key):
                raise SchemaValidationException(str(key))
            if key not in obj:
                raise FieldNotFoundException(key)
            return obj[key]
        elif isinstance(obj, list):
            if not isinstance(key, int):
                raise SchemaValidationException(str(key))
            try:
                return obj[key]
            except IndexError:
                raise SchemaValidationException(str(key))
        else:
            raise SchemaValidationException(str(key))
